export function getAuditEventById(id: string): AuditEvent | undefined {
  return auditEvents.find((e) => e.id === id);
}

export function getAuditEventsForTask(taskId: string): AuditEvent[] {
  return auditEvents
    .filter((e) => e.taskId === taskId)
    .sort((a, b) => new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime());
}

export function getAuditEventsByType(type: AuditEvent["type"]): AuditEvent[] {
  return auditEvents.filter((e) => e.type === type);
}
